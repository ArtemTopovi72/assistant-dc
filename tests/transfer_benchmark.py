def run_scenario(s):
    ctx = Ctx()
    rec = {"id": s["id"], "category": s["category"],
           "target": os.path.basename(s["target"]),
           "refs": [os.path.basename(r[0]) for r in s["refs"]],
           "instruction": s["instruction"], "face_sensitive": s["face_sensitive"],
           "target_region": s["tmask"], "source_region": [r[2] for r in s["refs"]]}
    if not os.path.exists(s["target"]):
        rec.update(success=False, error="target image missing"); return rec
    tmask = _ellipse_mask(s["target"], s["tmask"], s["id"] + "_t") if s["tmask"] else None
    refs = []
    for path, role, sm in s["refs"]:
        eff = path
        if sm:
            mp = _ellipse_mask(path, sm, s["id"] + "_src")
            cropped = im.crop_to_mask(path, mp)
            if cropped:
                eff = cropped
        refs.append(im.ReferenceImage(eff, role))
    t0 = time.time()
    try:
        out = im.plan_and_execute_transfer(ctx, s["target"], refs, s["instruction"],
                                           mask_override=tmask, timeout=520)
    except Exception as exc:
        rec.update(success=False, error=f"{type(exc).__name__}: {exc}",
                   runtime=round(time.time() - t0, 1))
        return rec
    rec["runtime"] = round(time.time() - t0, 1)
    rec["mode"] = "contained (mask+composite-back)"
    if out and os.path.exists(out):
        W, H = Image.open(s["target"]).size
        ow, oh = Image.open(out).size
        rec["output"] = os.path.basename(out)
        rec["output_dims"] = [ow, oh]
        rec["dims_preserved"] = (ow, oh) == (W, H)
        try:
            import identity_metrics as idm
            c = idm.identity_cosine(s["target"], out)
            rec["identity_cosine"] = round(c, 4) if c is not None else None
        except Exception:
            rec["identity_cosine"] = None
        dst = os.path.join(OUT, f"{s['id']}_{s['category'].replace('/','-')}.png")
        shutil.copy(out, dst)
        rec["review_file"] = os.path.relpath(dst, os.path.dirname(os.path.dirname(__file__)))
        rec["success"] = True
    else:
        rec.update(success=False, error="no output (see logs)")
    return rec


if __name__ == "__main__":
    import logging
    logging.basicConfig(level=logging.WARNING, format="%(name)s: %(message)s")
    args = sys.argv[1:]
    if args == ["all"]:
        chosen = SCENARIOS
    elif args:
        chosen = [s for s in SCENARIOS if s["id"] in args]
    else:
        chosen = [s for s in SCENARIOS if s["id"] in ("s2", "s3", "s4", "s7", "s9")]
    report = []
    for s in chosen:
        print(f"--- {s['id']} {s['category']} ---", flush=True)
        rec = run_scenario(s)
        print(json.dumps(rec, ensure_ascii=False), flush=True)
        report.append(rec)
    rp = os.path.join(OUT, "report.json")
    json.dump(report, open(rp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    ok = sum(1 for r in report if r.get("success"))
    print(f"\n=== {ok}/{len(report)} produced output; report -> {rp} ===")
