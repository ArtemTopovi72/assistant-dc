class Ctx:
    def __init__(self):
        self.cancel_event = threading.Event()
        self.last_image_prompt = ""
        self.api_lock = threading.Lock()
        self.api_min_interval = 0.0
        self.last_api_call_time = 0.0
    def is_cancelled(self): return False
    def set_stage(self, *a): pass


def _ellipse_mask(src, box_frac, name):
    """box_frac = (x0,y0,x1,y1) as fractions of (W,H)."""
    W, H = Image.open(src).size
    m = Image.new("L", (W, H), 0)
    x0, y0, x1, y1 = box_frac
    ImageDraw.Draw(m).ellipse((int(W * x0), int(H * y0), int(W * x1), int(H * y1)), fill=255)
    p = os.path.join(MASKDIR, name + ".png")
    m.save(p)
    return p


# Each scenario: id, category, target, refs[(path,role,src_mask_frac|None)],
# instruction, target_mask_frac|None, face_sensitive(bool)
def _S(id, cat, target, refs, instr, tmask=None, face=False):
    return {"id": id, "category": cat, "target": target, "refs": refs,
            "instruction": instr, "tmask": tmask, "face_sensitive": face}

