"""Live Transfer benchmark harness (needs ComfyUI + GPU).

Defines a 30-scenario matrix across the categories in the spec (clothing,
accessories, hair/face, tattoo/face-sensitive, objects, multi-person, region
selection, failure cases) and runs a chosen subset against REAL desktop images,
recording every required field (source, dest, regions, output, mode, runtime,
success) plus identity/face-preservation cosine and output dimensions.

It is deterministic in setup (masks are generated by box/ellipse functions at
known coordinates so a run is reproducible) and writes a JSON report +
copies each output to tests/bench_out/ for visual review.

Usage:
    venv/Scripts/python.exe tests/transfer_benchmark.py            # default subset
    venv/Scripts/python.exe tests/transfer_benchmark.py all        # all defined
    venv/Scripts/python.exe tests/transfer_benchmark.py s1 s7 s12  # by id
"""
